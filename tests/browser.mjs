import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { PNG } from 'pngjs';
import jsQR from 'jsqr';
import { mkdir, readFile } from 'node:fs/promises';
import { preview } from '../scripts/preview.mjs';
const { server } = preview(0);
await new Promise(resolve => server.on('listening', resolve));
const base = 'http://127.0.0.1:' + server.address().port;
let browser;
try {
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  const errors = [], requests = [];
  context.on('page', page => page.on('pageerror', e => errors.push(e.message)));
  context.on('request', request => requests.push(request.url()));
  const page = await context.newPage();
  await mkdir('test-results', { recursive: true });
  await page.goto(base); await page.screenshot({ path: 'test-results/home-mobile.png', fullPage: true });
  const publicLogo = page.getByRole('img', { name: 'Igreja Presbiteriana de Divinópolis', exact: true });
  assert.ok(await publicLogo.evaluate(img => img.complete && img.naturalWidth > 0 && img.src.startsWith('data:image/png;base64,')), 'Logotipo oficial carregado localmente na página pública');
  for (const width of [320, 390, 768, 1280]) {
    await page.setViewportSize({ width, height: 900 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Página inicial sem transbordamento em ' + width);
  }
  await page.screenshot({ path: 'test-results/home-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'FAZER MINHA INSCRIÇÃO' }).click();
  await page.getByLabel('Nome do responsável', { exact: true }).fill('José da Silva');
  await page.getByLabel('WhatsApp com DDD', { exact: true }).fill('(37) 99999-1234');
  const plus = key => page.locator('#plus-' + key).click();
  await plus('spouse'); await plus('adultGuests'); await plus('childGuests'); await plus('childGuests');
  await page.locator('#minus-childGuests').click();
  assert.match(await page.locator('#live-summary').innerText(), /340,00/);
  assert.equal(await page.locator('#plus-spouse').isDisabled(), true);
  await page.locator('#minus-adultMembers').click();
  assert.equal(await page.locator('#quantity-spouse').innerText(), '0');
  assert.equal(await page.locator('#plus-spouse').isDisabled(), true);
  await plus('adultMembers'); await plus('spouse');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Formulário não transborda no celular');
  await page.screenshot({ path: 'test-results/form-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'CONFERIR INSCRIÇÃO' }).click();
  assert.match(await page.locator('#review-summary').innerText(), /340,00/);
  assert.match(await page.locator('#review-summary').innerText(), /4 pessoas/);
  await page.getByRole('button', { name: 'CONFIRMAR E PAGAR COM PIX' }).click();
  await page.locator('#qr svg').waitFor();
  const id = await page.locator('#registration-id').innerText(), link = await page.locator('#private-link').inputValue();
  assert.match(id, /^IPD26[A-F0-9]{16}$/); assert.match(link, /#id=.*&token=/);
  const png = PNG.sync.read(await page.locator('#qr').screenshot());
  assert.equal(jsQR(new Uint8ClampedArray(png.data), png.width, png.height)?.data, await page.locator('#pix-code').inputValue(), 'QR renderizado decodificado independentemente');
  await page.screenshot({ path: 'test-results/pix-mobile.png', fullPage: true });
  await page.getByText('Enviar comprovante (opcional)', { exact: true }).click();
  await page.locator('#proof-file').setInputFiles({ name: 'teste.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\nSIMULACAO DE TESTE') });
  await page.getByRole('button', { name: 'ENVIAR COMPROVANTE', exact: true }).click();
  await page.getByText(/Comprovante recebido em/).waitFor();
  assert.equal(await page.locator('#payment-status').innerText(), 'AGUARDANDO CONFIRMAÇÃO');
  await page.getByRole('button', { name: 'JÁ FIZ O PIX' }).click();
  await page.getByText('Aviso recebido. Aguarde a conferência bancária pela tesouraria.').waitFor();
  assert.equal(await page.locator('#payment-status').innerText(), 'AGUARDANDO CONFIRMAÇÃO');
  const admin = await context.newPage(); await admin.goto(base + '/admin');
  const adminLogo = admin.getByRole('img', { name: 'Igreja Presbiteriana de Divinópolis', exact: true });
  assert.ok(await adminLogo.evaluate(img => img.complete && img.naturalWidth > 0 && img.src.startsWith('data:image/png;base64,')), 'Logotipo oficial carregado localmente na administração');
  await admin.getByText('José da Silva', { exact: true }).waitFor();
  await admin.getByLabel('Pesquisar inscrição').fill('jose');
  assert.match(await admin.locator('#result-count').innerText(), /1 inscrição/);
  await admin.getByLabel('Pesquisar inscrição').fill('37999991234'); assert.match(await admin.locator('#result-count').innerText(), /1 inscrição/);
  const proofPromise = admin.waitForEvent('download'); await admin.getByRole('button', { name: 'Baixar comprovante', exact: true }).click();
  assert.match(await readFile(await (await proofPromise).path(), 'utf8'), /SIMULACAO DE TESTE/);
  await admin.getByRole('button', { name: 'CONFIRMAR PAGAMENTO', exact: true }).click();
  await admin.getByLabel('Referência do recebimento no extrato do Itaú').fill('TESTE SIMULADO — extrato 17/10 12h');
  await admin.locator('#submit-action').click(); await admin.getByText('PAGO', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Atualizar situação do pagamento' }).click();
  await page.getByText('Sua presença está confirmada.').waitFor();
  assert.equal(await page.locator('#pix-section').isVisible(), false);
  const receiptPromise = page.waitForEvent('download'); await page.getByRole('button', { name: 'SALVAR CONFIRMAÇÃO', exact: true }).click();
  const receipt = await receiptPromise; assert.match(await readFile(await receipt.path(), 'utf8'), /Valor pago: R\$\s340,00/);
  await page.screenshot({ path: 'test-results/receipt-mobile.png', fullPage: true });
  const consulta = await context.newPage(); await consulta.goto(link); await consulta.getByText('Sua presença está confirmada.').waitFor();
  await admin.getByRole('tab', { name: 'Conferência de entrada' }).click();
  await admin.getByLabel('Pesquisar inscrição').fill(id);
  await admin.getByRole('button', { name: 'CONFIRMAR ENTRADA', exact: true }).click();
  await admin.getByText('ENTRADA REGISTRADA', { exact: true }).waitFor();
  assert.equal(await admin.getByRole('button', { name: 'CONFIRMAR ENTRADA', exact: true }).count(), 0);
  await admin.getByLabel('Entrada', { exact: true }).selectOption('pending'); assert.match(await admin.locator('#result-count').innerText(), /0 inscrições/);
  await admin.getByLabel('Entrada', { exact: true }).selectOption('entered'); assert.match(await admin.locator('#result-count').innerText(), /1 inscrição/);
  await admin.setViewportSize({ width: 1280, height: 900 }); await admin.screenshot({ path: 'test-results/admin-desktop.png', fullPage: true });
  const csvPromise = admin.waitForEvent('download'); await admin.getByRole('button', { name: 'EXPORTAR RELATÓRIO CSV' }).click();
  assert.match(await readFile(await (await csvPromise).path(), 'utf8'), /José da Silva/);
  assert.deepEqual(errors, [], 'Nenhum erro JavaScript');
  assert.ok(requests.every(url => url.startsWith(base) || url.startsWith('data:')), 'Sem QR ou dados enviados a serviços externos');
  console.log('Navegador: responsividade 320–1280px, contadores, resumo, Pix decodificado, aviso pendente, tesouraria, consulta por token, recibo, pesquisa por nome/telefone/número, check-in e CSV verificados.');
} finally { await browser?.close(); await new Promise(resolve => server.close(resolve)); }
